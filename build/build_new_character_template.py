"""Derives characters/new-character.html (a blank draft for the DM to build a new
PLAYER character) from sheet_template.html. Very close to build_npc_template.py's
ad-hoc NPC page, but:
- "Save to Character Sheets folder" stays enabled, writing to Character Sheets/
  (not NPCs/) - the filename is computed live from the character's current name,
  since there's no source file yet when the draft is created
- once saved + regenerated, this becomes a real character.html like any other
  player - the draft page itself is just scratch space to get there
- drafts are listed on the DM Dashboard under "Character Drafts" so in-progress
  work isn't lost if the DM navigates away before saving
"""
import os

SRC = os.path.join(os.path.dirname(__file__), "sheet_template.html")
OUT = os.path.join(os.path.dirname(__file__), "new_character_template.html")

html = open(SRC).read()

html = html.replace(
    "<title>__CHARACTER_NAME__ — Character Sheet</title>",
    "<title>New Character</title>"
)

html = html.replace(
    '<body>\n\n<nav class="tabnav" id="tabNav">',
    '''<body>

<div id="lockScreen" class="lock-screen">
  <div class="lock-card">
    <h1 style="font-size:1.3rem;">DM Access Required</h1>
    <p style="color:var(--text-dim);font-size:0.85rem;">Creating a character is a DM tool. Enter DM mode first.</p>
    <a class="reset-btn" href="../dm.html" style="display:inline-block;width:auto;padding:9px 18px;">Go to DM Dashboard</a>
  </div>
</div>

<div id="appRoot" hidden>
<nav class="tabnav" id="tabNav">'''
)

html = html.replace(
    '''<div class="toplinks">
  <a class="backlink" href="../index.html" style="margin-bottom:0;">&larr; All characters</a>
  <a class="comparelink" href="../compare.html" id="compareLink" hidden>⇄ Compare players</a>
</div>''',
    '''<div class="toplinks">
  <a class="backlink" href="../dm.html" style="margin-bottom:0;">&larr; DM Dashboard</a>
  <a id="compareLink" hidden></a>
  <button class="comparelink" onclick="openImportModal()" style="background:none;font-family:inherit;cursor:pointer;">📥 Import JSON</button>
</div>

<div class="modal-overlay" id="importModal" hidden onclick="if(event.target===this) closeImportModal()">
  <div class="modal-card">
    <div class="modal-top">
      <div>
        <div class="modal-title">Import Character JSON</div>
        <div class="modal-level" style="text-transform:none;letter-spacing:0;">Paste JSON generated by Claude (or exported from another sheet) to fill in this character.</div>
      </div>
      <button class="modal-close" onclick="closeImportModal()">✕</button>
    </div>
    <textarea id="importTextarea" class="edit-input wide" rows="10" placeholder="{ &quot;name&quot;: &quot;...&quot;, ... }" style="font-family:monospace;font-size:0.78rem;"></textarea>
    <div id="importError" style="color:var(--bad);font-size:0.8rem;margin-top:6px;"></div>
    <button class="reset-btn save-folder-btn" style="margin-top:10px;" onclick="performImport()">Import</button>
  </div>
</div>'''
)

html = html.replace(
    '''<button class="reset-btn" onclick="resetProgress()">Reset tracked stats (HP, spell slots, notes…)</button>
<div class="footer-note">Progress and edits are saved on this device only.</div>

</div>''',
    '''<button class="reset-btn" onclick="resetProgress()">Reset tracked stats (HP, spell slots, notes…)</button>
<button class="reset-btn" onclick="deleteDraft()" style="border-color:var(--accent-2);color:#f4a68a;">🗑 Delete this draft</button>
<div class="footer-note">This draft is stored on this device only until you tap "Save to Character Sheets folder" below and it gets rebuilt into a real page.</div>

</div>'''
)

html = html.replace(
    "  .backlink{display:inline-block;margin-bottom:10px;color:var(--text-dim);font-size:0.8rem;text-decoration:none;}",
    """  .backlink{display:inline-block;margin-bottom:10px;color:var(--text-dim);font-size:0.8rem;text-decoration:none;}
  .lock-screen{min-height:100vh;display:flex;align-items:center;justify-content:center;padding:24px;}
  .lock-card{background:var(--panel);border:1px solid var(--border);border-radius:14px;
    padding:28px 24px;max-width:360px;text-align:center;}
  .lock-card h1{font-family:Georgia,"Times New Roman",serif;}
  .lock-card p{margin:10px 0 16px;}"""
)

html = html.replace(
    '''const DATA = __CHARACTER_DATA__;''',
    '''const params = new URLSearchParams(location.search);
let DRAFT_ID = params.get("id");
if(!DRAFT_ID){
  DRAFT_ID = "char-" + Date.now().toString(36) + Math.random().toString(36).slice(2,7);
  const url = new URL(location.href);
  url.searchParams.set("id", DRAFT_ID);
  history.replaceState(null, "", url);
}
const DATA = {
  id: DRAFT_ID,
  name: "New Character",
  species: "",
  classes: [{id:"class1", name:"", level:1, hitDie:8, subclass:""}],
  abilities: {str:10,dex:10,con:10,int:10,wis:10,cha:10},
  proficientSaves: [],
  skillProficiencies: [],
  skillExpertise: [],
  hp: {max:10, current:10, temp:0},
  speed: 30,
  conditions: [],
  exhaustion: 0,
  deathSaves: {successes:0, failures:0},
  inspiration: false,
  spellSlots: {},
  spellsPrepared: [],
  currency: {cp:0,sp:0,ep:0,gp:0,pp:0},
  inventory: [],
  notes: "",
  journal: {entries:[], npcs:[], quests:[], goals:[]},
  background: "",
  customFeatures: []
};'''
)

html = html.replace(
    '''charData = loadCharData();
try{ activeTab = localStorage.getItem(TAB_KEY) || "play"; }catch(e){}
setTab(activeTab);
renderAll();''',
    '''function slugifyName(name){
  return (name || "character").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "") || "character";
}
function syncDraftRegistry(){
  try{
    const raw = localStorage.getItem("dnd-new-character-list");
    let list = raw ? JSON.parse(raw) : [];
    const idx = list.findIndex(n => n.id === DATA.id);
    const entry = {id: DATA.id, name: charData.name || "New Character"};
    if(idx === -1) list.push(entry); else list[idx] = entry;
    localStorage.setItem("dnd-new-character-list", JSON.stringify(list));
  }catch(e){}
}
function deleteDraft(){
  const name = charData.name || "this draft";
  if(!confirm('This permanently deletes the draft "' + name + '" from this device. This cannot be undone. Continue?')) return;
  const typed = prompt('Type the character\\'s exact name to confirm deletion:\\n\\n"' + name + '"');
  if(typed !== name){
    toast(name, typed === null ? "Deletion cancelled" : "Name didn't match — nothing was deleted");
    return;
  }
  if(!confirm('Last check: permanently delete the draft "' + name + '"? There is no undo.')) return;
  try{
    localStorage.removeItem(STORE_KEY);
    localStorage.removeItem(EDIT_KEY);
    const raw = localStorage.getItem("dnd-new-character-list");
    let list = raw ? JSON.parse(raw) : [];
    list = list.filter(n => n.id !== DATA.id);
    localStorage.setItem("dnd-new-character-list", JSON.stringify(list));
  }catch(e){}
  location.href = "../dm.html";
}

function openImportModal(){
  document.getElementById("importError").textContent = "";
  document.getElementById("importModal").hidden = false;
}
function closeImportModal(){
  document.getElementById("importModal").hidden = true;
}
function performImport(){
  const ta = document.getElementById("importTextarea");
  const errEl = document.getElementById("importError");
  errEl.textContent = "";
  let parsed;
  try{
    parsed = JSON.parse(ta.value);
  }catch(e){
    errEl.textContent = "That doesn't look like valid JSON: " + e.message;
    return;
  }
  if(!parsed || typeof parsed !== "object" || Array.isArray(parsed) || !parsed.name){
    errEl.textContent = "JSON is missing required fields (at least a \\"name\\").";
    return;
  }
  parsed.id = DATA.id; // keep this draft's existing id/URL - importing replaces its data, not its identity
  charData = normalizeCharData(parsed);
  saveCharData();
  renderAll();
  syncDraftRegistry();
  closeImportModal();
  toast(charData.name, "Imported");
}

if(!isDM()){
  document.getElementById("lockScreen").hidden = false;
  document.getElementById("appRoot").hidden = true;
} else {
  document.getElementById("lockScreen").hidden = true;
  document.getElementById("appRoot").hidden = false;
  charData = loadCharData();
  try{ activeTab = localStorage.getItem(TAB_KEY) || "play"; }catch(e){}
  setTab(activeTab);
  renderAll();
  syncDraftRegistry();
}'''
)

# renderAll() keeps the registry name in sync on every edit while on the page
html = html.replace(
    "  renderNotes();\n  renderJournal();\n}",
    "  renderNotes();\n  renderJournal();\n  if(typeof syncDraftRegistry === \"function\") syncDraftRegistry();\n}"
)

# The filename doesn't exist yet (no source file until first save), and can
# change as the DM renames the character, so compute it fresh at save time
# instead of using a fixed embedded filename.
html = html.replace(
    'const SOURCE_FILENAME = "__SOURCE_FILENAME__";',
    'let SOURCE_FILENAME = "new-character.json"; // placeholder so the Save button shows; recomputed on each save'
)
html = html.replace(
    '''async function saveToFolder(){
  if(!FS_SUPPORTED || !SOURCE_FILENAME) return;
  try{
    const dir = await getDirHandle(false);
    const fileHandle = await dir.getFileHandle(SOURCE_FILENAME, {create:true});''',
    '''async function saveToFolder(){
  if(!FS_SUPPORTED) return;
  SOURCE_FILENAME = slugifyName(charData.name) + ".json";
  try{
    const dir = await getDirHandle(false);
    const fileHandle = await dir.getFileHandle(SOURCE_FILENAME, {create:true});'''
)

# Once actually saved, this stops being a "draft" - remove it from the local
# drafts registry immediately so reopening this same URL later won't have it
# show up a second time once it's also pushed as a real character.
html = html.replace(
    '    toast(charData.name, "Saved to " + SOURCE_FILENAME);',
    '''    toast(charData.name, "Saved to " + SOURCE_FILENAME);
    try{
      const raw = localStorage.getItem("dnd-new-character-list");
      let list = raw ? JSON.parse(raw) : [];
      list = list.filter(n => n.id !== DATA.id);
      localStorage.setItem("dnd-new-character-list", JSON.stringify(list));
    }catch(e){}'''
)

# close the appRoot wrapper div right before </body>
html = html.replace("</body>", "</div>\n</body>")

open(OUT, "w").write(html)
print("wrote", OUT)
