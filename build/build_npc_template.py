"""Derives characters/npc.html (a generic, ad-hoc NPC/monster sheet) from sheet_template.html.
Reuses ~all of the player sheet template/logic, but:
- loads a blank character keyed by a ?id= query param instead of embedded per-character JSON
- is gated behind DM auth (locked screen if not isDM())
- links back to the DM dashboard instead of the player index
- adds a delete button and syncs a simple NPC name registry for dm.html to list
"""
import os

SRC = os.path.join(os.path.dirname(__file__), "sheet_template.html")
OUT = os.path.join(os.path.dirname(__file__), "npc_template.html")

html = open(SRC).read()

html = html.replace(
    "<title>__CHARACTER_NAME__ — Character Sheet</title>",
    "<title>NPC / Monster</title>"
)

html = html.replace(
    '<body>\n\n<nav class="tabnav" id="tabNav">',
    '''<body>

<div id="lockScreen" class="lock-screen">
  <div class="lock-card">
    <h1 style="font-size:1.3rem;">DM Access Required</h1>
    <p style="color:var(--text-dim);font-size:0.85rem;">NPC and monster sheets are hidden from players. Enter DM mode first.</p>
    <a class="reset-btn" href="../dm.html" style="display:inline-block;width:auto;padding:9px 18px;">Go to DM Dashboard</a>
  </div>
</div>

<div id="appRoot" hidden>
<nav class="tabnav" id="tabNav">'''
)

html = html.replace(
    '''<div class="toplinks">
  <a class="backlink" href="../index.html" style="margin-bottom:0;">&larr; All characters</a>
  <a class="comparelink" href="../compare.html" id="compareLink" hidden>⇄ Compare players</a>
</div>''',
    '''<div class="toplinks">
  <a class="backlink" href="../dm.html" style="margin-bottom:0;">&larr; DM Dashboard</a>
  <a id="compareLink" hidden></a>
  <button class="comparelink" onclick="openImportModal()" style="background:none;font-family:inherit;cursor:pointer;">📥 Import JSON</button>
</div>

<div class="modal-overlay" id="importModal" hidden onclick="if(event.target===this) closeImportModal()">
  <div class="modal-card">
    <div class="modal-top">
      <div>
        <div class="modal-title">Import NPC JSON</div>
        <div class="modal-level" style="text-transform:none;letter-spacing:0;">Paste JSON generated by Claude (or exported from another sheet) to fill in this NPC.</div>
      </div>
      <button class="modal-close" onclick="closeImportModal()">✕</button>
    </div>
    <textarea id="importTextarea" class="edit-input wide" rows="10" placeholder="{ &quot;name&quot;: &quot;...&quot;, ... }" style="font-family:monospace;font-size:0.78rem;"></textarea>
    <div id="importError" style="color:var(--bad);font-size:0.8rem;margin-top:6px;"></div>
    <button class="reset-btn save-folder-btn" style="margin-top:10px;" onclick="performImport()">Import</button>
  </div>
</div>'''
)

html = html.replace(
    '''<button class="reset-btn" onclick="resetProgress()">Reset tracked stats (HP, spell slots, notes…)</button>
<div class="footer-note">Progress and edits are saved on this device only.</div>

</div>''',
    '''<button class="reset-btn" onclick="resetProgress()">Reset tracked stats (HP, spell slots, notes…)</button>
<button class="reset-btn" onclick="deleteNpc()" style="border-color:var(--accent-2);color:#f4a68a;">🗑 Delete this NPC/monster</button>
<div class="footer-note">This NPC/monster is stored on this device only — it will not appear on other devices or the public site.</div>

</div>'''
)

html = html.replace(
    "  .backlink{display:inline-block;margin-bottom:10px;color:var(--text-dim);font-size:0.8rem;text-decoration:none;}",
    """  .backlink{display:inline-block;margin-bottom:10px;color:var(--text-dim);font-size:0.8rem;text-decoration:none;}
  .lock-screen{min-height:100vh;display:flex;align-items:center;justify-content:center;padding:24px;}
  .lock-card{background:var(--panel);border:1px solid var(--border);border-radius:14px;
    padding:28px 24px;max-width:360px;text-align:center;}
  .lock-card h1{font-family:Georgia,"Times New Roman",serif;}
  .lock-card p{margin:10px 0 16px;}"""
)

html = html.replace(
    '''const DATA = __CHARACTER_DATA__;''',
    '''const params = new URLSearchParams(location.search);
let NPC_ID = params.get("id");
if(!NPC_ID){
  NPC_ID = "npc-" + Date.now().toString(36) + Math.random().toString(36).slice(2,7);
  const url = new URL(location.href);
  url.searchParams.set("id", NPC_ID);
  history.replaceState(null, "", url);
}
const DATA = {
  id: NPC_ID,
  name: "New NPC",
  species: "",
  classes: [{id:"role", name:"NPC", level:1, hitDie:8, subclass:""}],
  abilities: {str:10,dex:10,con:10,int:10,wis:10,cha:10},
  proficientSaves: [],
  skillProficiencies: [],
  skillExpertise: [],
  hp: {max:10, current:10, temp:0},
  speed: 30,
  conditions: [],
  exhaustion: 0,
  deathSaves: {successes:0, failures:0},
  inspiration: false,
  spellSlots: {},
  spellsPrepared: [],
  currency: {cp:0,sp:0,ep:0,gp:0,pp:0},
  inventory: [],
  notes: "",
  journal: {entries:[], npcs:[], quests:[], goals:[]},
  background: "",
  customFeatures: []
};'''
)

html = html.replace(
    '''charData = loadCharData();
try{ activeTab = localStorage.getItem(TAB_KEY) || "play"; }catch(e){}
setTab(activeTab);
renderAll();''',
    '''function syncNpcRegistry(){
  try{
    const raw = localStorage.getItem("dnd-npc-list");
    let list = raw ? JSON.parse(raw) : [];
    const idx = list.findIndex(n => n.id === DATA.id);
    const entry = {id: DATA.id, name: charData.name || "New NPC"};
    if(idx === -1) list.push(entry); else list[idx] = entry;
    localStorage.setItem("dnd-npc-list", JSON.stringify(list));
  }catch(e){}
}
function deleteNpc(){
  const name = charData.name || "this NPC";
  if(!confirm('This permanently deletes "' + name + '" from this device. This cannot be undone. Continue?')) return;
  const typed = prompt('Type the NPC\\'s exact name to confirm deletion:\\n\\n"' + name + '"');
  if(typed !== name){
    toast(name, typed === null ? "Deletion cancelled" : "Name didn't match — nothing was deleted");
    return;
  }
  if(!confirm('Last check: permanently delete "' + name + '"? There is no undo.')) return;
  try{
    localStorage.removeItem(STORE_KEY);
    localStorage.removeItem(EDIT_KEY);
    const raw = localStorage.getItem("dnd-npc-list");
    let list = raw ? JSON.parse(raw) : [];
    list = list.filter(n => n.id !== DATA.id);
    localStorage.setItem("dnd-npc-list", JSON.stringify(list));
  }catch(e){}
  location.href = "../dm.html";
}

function openImportModal(){
  document.getElementById("importError").textContent = "";
  document.getElementById("importModal").hidden = false;
}
function closeImportModal(){
  document.getElementById("importModal").hidden = true;
}
function performImport(){
  const ta = document.getElementById("importTextarea");
  const errEl = document.getElementById("importError");
  errEl.textContent = "";
  let parsed;
  try{
    parsed = JSON.parse(ta.value);
  }catch(e){
    errEl.textContent = "That doesn't look like valid JSON: " + e.message;
    return;
  }
  if(!parsed || typeof parsed !== "object" || Array.isArray(parsed) || !parsed.name){
    errEl.textContent = "JSON is missing required fields (at least a \\"name\\").";
    return;
  }
  parsed.id = DATA.id; // keep this NPC's existing id/URL - importing replaces its data, not its identity
  charData = normalizeCharData(parsed);
  saveCharData();
  renderAll();
  syncNpcRegistry();
  closeImportModal();
  toast(charData.name, "Imported");
}

if(!isDM()){
  document.getElementById("lockScreen").hidden = false;
  document.getElementById("appRoot").hidden = true;
} else {
  document.getElementById("lockScreen").hidden = true;
  document.getElementById("appRoot").hidden = false;
  charData = loadCharData();
  try{ activeTab = localStorage.getItem(TAB_KEY) || "play"; }catch(e){}
  setTab(activeTab);
  renderAll();
  syncNpcRegistry();
}'''
)

# renderAll() keeps the registry name in sync on every edit while on the page
html = html.replace(
    "  renderNotes();\n  renderJournal();\n}",
    "  renderNotes();\n  renderJournal();\n  if(typeof syncNpcRegistry === \"function\") syncNpcRegistry();\n}"
)

# NPCs have no source JSON file in Character Sheets/ - they only live in the
# DM's browser storage - so disable the "save to folder" feature for them.
html = html.replace('const SOURCE_FILENAME = "__SOURCE_FILENAME__";', 'const SOURCE_FILENAME = "";')

# Ad-hoc local drafts have no stable id to key a Firestore doc on and are
# meant to stay browser-only (see build/README.md) - no live sync for these.
html = html.replace("__FS_SYNC_ENABLED__", "false")
html = html.replace("__FS_COLLECTION__", "unused")
html = html.replace("__LEGACY_FOLDER_SAVE_ENABLED__", "false")

# close the appRoot wrapper div right before </body>
html = html.replace("</body>", "</div>\n</body>")

open(OUT, "w").write(html)
print("wrote", OUT)
